// Write ui/kits/fixtures.json from ui/kits/fixtures.in.json.
//
// The designer kits exist three times: plain modules in `ui/kits/` for the
// reference UI, TypeScript in `@godwinmix/client`, Python in `godwinmix`. Three
// implementations of one algorithm drift, so the algorithm has one source of
// truth (`ui/kits/`) and its behaviour has one source of truth as well: this
// file runs the reference kit over a list of inputs and records what it
// answered, and the TypeScript and Python suites replay the same file and
// assert the same answers. A port that disagrees fails in its own language's
// test run, naming the case.
//
//   node dev/kit-fixtures.mjs           write ui/kits/fixtures.json
//   node dev/kit-fixtures.mjs --check   fail if it would change (CI)
//
// Nothing in ui/kits that this touches imports a DOM, which is what lets it run
// under plain node with no toolchain.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { SceneMirror } from "../ui/kits/protocol/mirror.js";
import { Prediction, mergeProps } from "../ui/kits/protocol/predict.js";
import { gizmosFor, handlesFor, applyDrag } from "../ui/kits/canvas/gizmos.js";
import { snapTargets, snapDelta } from "../ui/kits/canvas/snap.js";
import { safeAreas } from "../ui/kits/canvas/safe.js";
import { describeForm, valuesOf, readForm, missing } from "../ui/kits/schema/describe.js";
import { layoutFor, applyRules, controlsOf } from "../ui/kits/schema/ui-schema.js";

const root = new URL("../ui/kits/", import.meta.url);
const input = JSON.parse(readFileSync(new URL("fixtures.in.json", root), "utf8"));
const out = {
  note:
    "Generated by dev/kit-fixtures.mjs from fixtures.in.json. The reference kit in ui/kits " +
    "answered these; the TypeScript and Python kits replay the file and must answer the same. " +
    "Do not edit by hand.",
  mirror: input.mirror.map(mirrorCase),
  predict: input.predict.map(predictCase),
  merge: input.merge.map((c) => ({ name: c.name, base: c.base, next: c.next, out: mergeProps(c.base, c.next) })),
  gizmos: input.gizmos.map(gizmoCase),
  handles: input.handles.map(handleCase),
  drag: input.drag.map(dragCase),
  snap: input.snap.map(snapCase),
  safe: input.safe.map((c) => ({ canvas: c.canvas, out: round(safeAreas(c.canvas)) })),
  schema: input.schema.map(schemaCase),
  read: input.read.map(readCase),
  uiSchema: input.uiSchema.map(uiCase),
};

function mirrorCase(c) {
  const mirror = new SceneMirror({ clientId: c.clientId });
  const results = [];
  for (const step of c.steps) {
    if (step.view) {
      mirror.applyView(step.view);
      results.push({ kind: "view" });
    } else {
      const r = mirror.applyPatch(step.patch);
      results.push({ kind: "patch", applied: r.applied, echo: r.echo, gap: r.gap, seq: r.seq });
    }
  }
  return {
    name: c.name,
    clientId: c.clientId,
    steps: c.steps,
    out: {
      steps: results,
      seq: mirror.seq,
      unknown: mirror.unknown,
      scenes: mirror.scenes().map((s) => s.id),
      items: Object.fromEntries(mirror.scenes().map((s) => [s.id, mirror.items(s.id).map((i) => i.id)])),
      names: Object.fromEntries([...mirror.records.values()].map((r) => [r.id, r.name === undefined ? null : r.name])),
    },
  };
}

function predictCase(c) {
  const p = new Prediction();
  const seqs = [];
  const settled = [];
  for (const [op, a, b] of c.ops) {
    if (op === "predict") seqs.push(p.predict(a, b));
    else settled.push(p.settle(a));
  }
  return {
    name: c.name,
    ops: c.ops,
    resolve: c.resolve,
    accepts: c.accepts,
    out: {
      seqs,
      settled,
      acked: p.acked,
      pending: [...p.pending.keys()].sort(),
      resolved: Object.fromEntries(Object.entries(c.resolve || {}).map(([item, server]) => [item, p.resolve(item, server)])),
      accepted: (c.accepts || []).map(([item, echo]) => p.accepts(item, echo)),
    },
  };
}

function gizmoCase(c) {
  const gizmos = gizmosFor(c.designer);
  return {
    name: c.name,
    designer: c.designer,
    out: gizmos.map((g) => ({ kind: g.kind, action: g.action, target: g.target, anchor: g.anchor })),
  };
}

function handleCase(c) {
  const handles = handlesFor(c.box, gizmosFor(c.designer));
  return {
    name: c.name,
    box: c.box,
    designer: c.designer,
    out: handles.map((h) => ({ kind: h.kind, action: h.action, x: r2(h.x), y: r2(h.y), dir: h.dir, cursor: h.cursor })),
  };
}

function dragCase(c) {
  const result = applyDrag(c.handle, c.start, c.dx, c.dy, c.mods || {});
  return {
    name: c.name,
    handle: c.handle,
    start: c.start,
    dx: c.dx,
    dy: c.dy,
    mods: c.mods || {},
    out: { props: round(result.props), box: result.box ? round(result.box) : null },
  };
}

function snapCase(c) {
  const targets = snapTargets(c.targets);
  const delta = snapDelta(c.box, targets, c.opts || {});
  return {
    name: c.name,
    targets: c.targets,
    box: c.box,
    opts: c.opts || {},
    out: { dx: r2(delta.dx), dy: r2(delta.dy), guides: delta.guides.map((g) => ({ axis: g.axis, at: r2(g.at), span: g.span.map(r2) })) },
  };
}

function schemaCase(c) {
  const form = describeForm(c.schema, c.value || {});
  return {
    name: c.name,
    schema: c.schema,
    value: c.value || {},
    out: {
      groups: form.groups,
      fields: form.fields.map((f) => ({
        name: f.name,
        kind: f.kind,
        group: f.group,
        required: f.required,
        visible: f.visible,
        unit: f.unit === undefined ? null : f.unit,
        value: f.value === undefined ? null : f.value,
        choices: f.choices ? f.choices.map((x) => x.value) : null,
      })),
    },
  };
}

/**
 * What a form sends back. Its own section because `describeForm` never reaches
 * `readForm`, which is where the three readers had quietly drifted apart.
 */
function readCase(c) {
  const form = describeForm(c.schema, c.value || {});
  const values = Object.assign({}, valuesOf(form), c.values || {});
  return {
    name: c.name,
    schema: c.schema,
    value: c.value || {},
    values: c.values || {},
    touched: c.touched || [],
    out: {
      read: readForm(form, values, new Set(c.touched || [])),
      missing: missing(form, values),
    },
  };
}

function uiCase(c) {
  const form = describeForm(c.schema, c.value || {});
  const layout = applyRules(layoutFor(form, c.ui), valuesOf(form));
  return {
    name: c.name,
    schema: c.schema,
    ui: c.ui,
    value: c.value || {},
    out: {
      controls: controlsOf(layout).map((n) => ({ field: n.field.name, control: n.control, visible: n.visible !== false, enabled: n.enabled !== false })),
    },
  };
}

// Two decimal places everywhere, so a port that computes in a different order
// is not failed by the last bit of a double.
function r2(v) {
  return typeof v === "number" ? Math.round(v * 100) / 100 : v;
}

function round(value) {
  if (Array.isArray(value)) return value.map(round);
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, round(v)]));
  }
  return r2(value);
}

const text = JSON.stringify(out, null, 2) + "\n";
const path = fileURLToPath(new URL("fixtures.json", root));
if (process.argv.includes("--check")) {
  const had = (() => {
    try {
      return readFileSync(path, "utf8");
    } catch {
      return "";
    }
  })();
  if (had !== text) {
    console.error("ui/kits/fixtures.json is out of date. Run: node dev/kit-fixtures.mjs");
    process.exit(1);
  }
  console.log("ui/kits/fixtures.json is current");
} else {
  writeFileSync(path, text);
  console.log(`wrote ${path}`);
}
