//! The Rust encoder against the page's own: the same text makes the same
//! modules as `ui/panels/channels/qr.js`, which phones have been scanning
//! since the channels page shipped. The expected grids were printed by that
//! file under Node.

use super::qr;

fn rows(text: &str) -> Vec<String> {
    qr::matrix(text).expect("it fits").iter().map(|r| r.iter().map(|d| if *d { '1' } else { '0' }).collect()).collect()
}

#[test]
fn a_short_text_is_the_same_version_1_code_the_page_draws() {
    let want = "111111100111101111111/100000100110101000001/101110101101101011101/101110101100101011101/101110101001101011101/100000101100101000001/111111101010101111111/000000001011100000000/101111100000101111100/011101010010100100001/001100110101010011110/111010000100000110100/111010100001010010101/000000001001111001001/111111100010101100010/100000101111111001001/101110101000100100100/101110101110100100100/101110101001010011100/100000100110000110100/111111101011010011110";
    assert_eq!(rows("hi").join("/"), want);
}

/// Version 7, four blocks and the version information: every part of the
/// layout a short text does not reach.
#[test]
fn an_invite_link_is_the_same_version_7_code_the_page_draws() {
    let link = "https://192.168.1.20:8443/join/#guest=ana-lopez&key=abcdefghijklmnopqrstuvwx&title=Ana%20Lopez&show=second-room";
    assert_eq!(rows(link), WANT_LONG);
}

#[test]
fn the_svg_has_the_quiet_zone_and_a_text_too_long_has_no_code() {
    let svg = qr::svg("hi").expect("a code");
    assert!(svg.starts_with("<svg") && svg.contains("viewBox=\"0 0 29 29\""), "{svg}");
    assert!(qr::svg(&"x".repeat(300)).is_none());
}

